#!/usr/bin/env python3
"""Write src/desk_sim/fluidity_matrix.rs: one test per fluidity case.

Every source OS x target OS x side x screen size x scenario. The cases on the
user's own layout (target on the right, laptop next to a 1440p monitor) run
with `cargo test`; the rest are `#[ignore]` and run in the weekly job with
`cargo test -- --ignored`. Rerun after changing the lists below.
"""

from pathlib import Path

SOURCES = ["gnome", "windows", "sway"]  # x11 has no capture backend
TARGETS = ["gnome", "windows", "sway", "x11"]
SIDES = ["Right", "Left", "Top", "Bottom"]
SIZES = 3  # fluidity::SIZES
SCENARIOS = [
    "CrossAndStop", "RoundTrip", "QuickReturn", "EdgeStart", "EdgeEnd",
    "NearCornerLow", "NearCornerHigh", "SlowCrawl", "Flick", "DragHold",
    "DragCross", "HandSwitch", "BothMice", "KeyHeldAcrossReturn",
    "HotkeyFromEither",
]
TWO_HANDS = {"HandSwitch", "BothMice", "HotkeyFromEither"}
# the user's desk runs in every `cargo test`
SHORT = ("Right", 1)


def snake(name: str) -> str:
    out = ""
    for ch in name:
        out += ("_" + ch.lower()) if ch.isupper() and out else ch.lower()
    return out


lines = [
    "//! Generated by scripts/gen-fluidity-matrix.py - do not edit by hand.",
    "//! One test per case of the fluidity matrix (see `fluidity.rs`).",
    "",
    "use input_capture::Position;",
    "",
    "use super::{",
    "    Personality,",
    "    fluidity::{Case, SIZES, Scenario, run},",
    "};",
    "",
]
count = short = 0
for src in SOURCES:
    for dst in TARGETS:
        for side in SIDES:
            for size in range(SIZES):
                for scenario in SCENARIOS:
                    if scenario in TWO_HANDS and dst == "x11":
                        continue
                    name = f"{src}_to_{dst}_{side.lower()}_size{size}_{snake(scenario)}"
                    is_short = (side, size) == SHORT
                    if not is_short:
                        lines.append("#[ignore = \"full matrix: cargo test -- --ignored\"]")
                    lines += [
                        "#[test]",
                        f"fn {name}() {{",
                        "    run(Case {",
                        f"        source: Personality::{src},",
                        f"        target: Personality::{dst},",
                        f"        side: Position::{side},",
                        f"        sizes: SIZES[{size}],",
                        f"        scenario: Scenario::{scenario},",
                        "    });",
                        "}",
                        "",
                    ]
                    count += 1
                    short += is_short
out = Path(__file__).resolve().parent.parent / "src/desk_sim/fluidity_matrix.rs"
out.write_text("\n".join(lines))
print(f"{count} cases ({short} in the short matrix) -> {out}")
